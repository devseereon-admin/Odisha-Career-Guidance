<script>
function updateTree(id) {

    const relations = ["Me", "Mother", "Father", "Brother/Cousin", "Sister/Cousin"];

    let box = document.querySelector(".t-content-" + id);

    let name = box.querySelectorAll("input")[0].value;
    let career = box.querySelectorAll("input")[1].value;

    let finalBox = box.querySelector(".final-box");

    // Store formatted content
  let display = `
    <div style="
        background:#0a8f2c;
        color:#fff;
        padding:6px 8px;
        border-radius:6px;
        font-size:12px;
        line-height:1.3;
        width:100%;
        box-sizing:border-box;
    ">
        ${relations[id-1]}: ${name}<br>
        ${career}
    </div>
`;

    finalBox.innerHTML = display;
}

function prepareDownload() {
    let data = [];

    for (let i = 1; i <= 5; i++) {
        let el = document.querySelector(".t-content-" + i);
        data.push(el.getAttribute("data-content") || "");
    }

    document.getElementById("finalData").value = JSON.stringify(data);
}
function downloadImage() {

    let tree = document.getElementById("tree-container");

    tree.classList.add("download-mode");

    setTimeout(() => {
      html2canvas(tree, {
    scale: 2,
    useCORS: true,
    scrollX: 0,
    scrollY: 0,
    windowWidth: document.documentElement.scrollWidth,
    windowHeight: document.documentElement.scrollHeight
}).then(canvas => {

            let link = document.createElement("a");
            link.download = "family-tree.png";
            link.href = canvas.toDataURL("image/png");
            link.click();

            tree.classList.remove("download-mode");

            // ✅ RESET INPUT FIELDS
            document.querySelectorAll("#tree-container input").forEach(input => {
                input.value = "";
            });

            // ✅ CLEAR FINAL BOXES
            document.querySelectorAll(".final-box").forEach(box => {
                box.innerHTML = "";
            });

        });
    }, 500);
}
</script>


