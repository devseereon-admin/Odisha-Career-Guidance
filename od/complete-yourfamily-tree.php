       function updateTree(id) {

    const relations = ["ମୁଁ", "ମା", "ବାପା", "ଭାଇ", "ଭଉଣୀ"];

    let box = document.querySelector(".t-content-" + id);

    let name = box.querySelectorAll("input")[0].value;
    let career = box.querySelectorAll("input")[1].value;

    let finalBox = box.querySelector(".final-box");

    let display = `
    <div style="
        background:#0a8f2c;
        color:#fff;
        padding:6px 8px;
        border-radius:6px;
        font-size:12px;
        line-height:1.3;
        width:100%;
    ">
        ${relations[id-1]}: ${name}<br>
        ${career}
    </div>
    `;

    finalBox.innerHTML = display;
}

function downloadImage() {

    let tree = document.getElementById("tree-container");

    tree.classList.add("download-mode");

    setTimeout(() => {

        html2canvas(tree, {
            scale: 2,
            useCORS: true,
            backgroundColor: "#ffffff"   // ✅ THIS FIXES BLACK BG
        }).then(canvas => {

            let link = document.createElement("a");
            link.download = "family-tree.png";
            link.href = canvas.toDataURL("image/png");
            link.click();

            tree.classList.remove("download-mode");

            // Reset inputs
            document.querySelectorAll("#tree-container input").forEach(input => {
                input.value = "";
            });

            // Clear boxes
            document.querySelectorAll(".final-box").forEach(box => {
                box.innerHTML = "";
            });

        });

    }, 500);
}

</script>


