	<h2>ଅସ୍ଵୀକାର ପତ୍ର</h2>
	<p class="centre_para">ଏଠାରେ ପ୍ରଦାନ କରାଯାଇଥିବା ବିଷୟବସ୍ତୁ ବୈଧ ଏବଂ ପ୍ରାସଙ୍ଗିକ ଅଟେ। ଏହି ସୂଚନା ଗତିଶୀଳ ଏବଂ ଭାରତ ଓ ବିଦେଶରେ ସଂଗଠନ, ଅଞ୍ଚଳ ଏବଂ ଚାକିରି କ୍ଷେତ୍ର ଅନୁଯାୟୀ ଭିନ୍ନ ଭିନ୍ନ ହେବ । ହାଇପରଲିଙ୍କ୍ ହୋଇଥିବା ବାହ୍ୟ ଉତ୍ସ / ୱେବସାଇଟ୍ ଗୁଡିକ ଗତିଶୀଳ ଏବଂ ସମୟ ସହିତ ପରିବର୍ତ୍ତନ ହୋଇପାରେ। ଏହି ସୂଚନା କେବଳ ସନ୍ଦର୍ଭ ଉଦ୍ଦେଶ୍ୟ ପାଇଁ ଅଟେ ଏବଂ କୌଣସି ବାଣିଜ୍ୟିକ ଉଦ୍ଦେଶ୍ୟ ପାଇଁ ବ୍ୟବହୃତ ହୋଇନପାରେ। ବିଭାଗ କୌଣସି ବ୍ୟକ୍ତି (ସଫଳତାର କାହାଣୀ) କିମ୍ବା ସଂଗଠନକୁ ସମର୍ଥନ କରେ ନାହିଁ।</p>
	<h4><b>ବୃତ୍ତି ପୃଷ୍ଠା</b></h4>
	<p class="content_para" style="font-size:20px;"><b>ଯୋଜନା : </b>ଏଠାରେ ପ୍ରଦାନ କରାଯାଇଥିବା ସୂଚନା ବୈଧ ଏବଂ ପ୍ରାସଙ୍ଗିକ ଅଟେ। ସମୟ କ୍ରମେ ଯୋଜନାରେ ପରିବର୍ତ୍ତନ ହୋଇପାରେ।</p>
	
	<p class="content_para" style="font-size:20px;"><b>ଶିକ୍ଷାନୁଷ୍ଠାନ: </b>ଏହି ତାଲିକା ସମ୍ପୂର୍ଣ୍ଣ ନୁହେଁ, ଏବଂ ଅନ୍ୟାନ୍ୟ ଶିକ୍ଷାନୁଷ୍ଠାନ ମଧ୍ୟ ଥାଇପାରେ, ଯାହା ୱେବସାଇଟ୍ ର ଶିକ୍ଷାନୁଷ୍ଠାନ ବିଭାଗରେ ସନ୍ଧାନ କରାଯାଇପାରିବ।</p>
	
	<p class="content_para" style="font-size:20px;"><b>ପ୍ରବେଶିକା ପରୀକ୍ଷା: </b>ଏଠାରେ ଦିଆଯାଇଥିବା ସୂଚନା ପ୍ରକାଶନ ତାରିଖ ଅନୁଯାୟୀ ବୈଧ ଏବଂ ପ୍ରାସଙ୍ଗିକ ଅଟେ । ତେବେ ନୀତିଗତ ନିଷ୍ପତ୍ତି ଆଧାରରେ ପ୍ରବେଶିକା ପରୀକ୍ଷାର ପ୍ରକାରରେ ପରିବର୍ତ୍ତନ ହୋଇପାରେ। ସନ୍ଦର୍ଭ ପାଇଁ ପ୍ରଦାନ କରାଯାଇଥିବା ବାହ୍ୟ ୱେବସାଇଟଗୁଡିକର ଲିଙ୍କଗୁଡିକ ମଧ୍ୟ ଗତିଶୀଳ ପ୍ରକୃତିର ଅଟେ ।</p>
	
	<p class="content_para" style="font-size:20px;"><b>ମେଧାବୃତ୍ତି: </b>ଏଠାରେ ପ୍ରଦାନ କରାଯାଇଥିବା ସୂଚନା ପ୍ରକାଶନ ତାରିଖ ଅନୁଯାୟୀ ବୈଧ ଏବଂ ପ୍ରାସଙ୍ଗିକ ଅଟେ । ଏହି ତାଲିକା ସମ୍ପୂର୍ଣ୍ଣ ନୁହେଁ, ଏବଂ ଏହି ସୂଚନା କିମ୍ବା ମେଧାବୃତ୍ତି ସୁଯୋଗରେ ପରିବର୍ତ୍ତନ ନୀତି କିମ୍ବା ବୃତ୍ତି ପ୍ରଦାନ କରୁଥିବା ଘରୋଇ କ୍ଷେତ୍ରର ସଂସ୍ଥାଗୁଡିକ ଦ୍ୱାରା ନିଷ୍ପତ୍ତି ଦ୍ୱାରା ଭିନ୍ନ ହୋଇପାରେ । ଅଧିକ ସୂଚନା ପାଇଁ, ୱେବସାଇଟର ମେଧାବୃତ୍ତି ବିଭାଗକୁ ଦେଖନ୍ତୁ।</p>
	
	<p class="content_para" style="font-size:20px;"><b>ଉଦ୍ୟୋଗ: </b>ଏହି କ୍ଷେତ୍ରରେ ଉଦ୍ୟୋଗକୁ କିପରି ଆକୃଷ୍ଟ କରାଯାଇପାରିବ ସେ ବିଷୟରେ ଏହି ସୂଚନା ଧାରଣା ପ୍ରଦାନ କରେ । ଏହି ଧାରଣାଗୁଡ଼ିକ ସମ୍ପୂର୍ଣ୍ଣ ନୁହେଁ, ଏବଂ ଅଧିକ ଅଭିନବ ଚିନ୍ତାଧାରାକୁ ପ୍ରୋତ୍ସାହିତ କରାଯାଏ ।</p>
		
	<p class="content_para" style="font-size:20px;"><b>ଦିବ୍ୟାଙ୍ଗ: </b>ଏହି ସୂଚନା ସମ୍ପୂର୍ଣ୍ଣ ନୁହେଁ ଏବଂ ବିଭିନ୍ନ ସଂଗଠନ ଏବଂ ଦିବ୍ୟାଙ୍ଗଙ୍କ ଭିନ୍ନ ଡିଗ୍ରୀ ଏବଂ ଅନୁଭୂତିରେ ଭିନ୍ନ ହେବ ।</p>
		
